/** Os lugares mais próximos de um ponto, até `raio` metros (linha reta). */
export function lugaresProximos(
  ponto: { lat: number; lng: number },
  tipo: TipoLugar,
  limite = 3,
  raio = 2000
): (Lugar & { distancia: number })[] {
  const vistos = new Set<string>();
  return lugares
    .filter((l) => l.tipo === tipo)
    .map((l) => ({ ...l, distancia: distanciaMetros(ponto, l) }))
    .filter((l) => l.distancia <= raio)
    .sort((a, b) => a.distancia - b.distancia)
    .filter((l) => (vistos.has(l.nome) ? false : (vistos.add(l.nome), true)))
    .slice(0, limite);
}
